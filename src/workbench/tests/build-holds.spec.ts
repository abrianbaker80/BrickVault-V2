import { expect } from '@playwright/test'
import { test } from './trusted'
import { audit, fixture, open, stock } from './bin-fixture'
import { holdPositionLink } from '../src/countLinks'

test('a witnessed shortage retains both builds until the owner releases units from the chosen hold', async ({ page }, info) => {
  const f = await fixture(page)
  await open(page, f.a)
  const row = stock(page).getByRole('list', { name: 'Receipt layers in this bin' }).getByRole('listitem').filter({ hasText: f.paid.purchase })
  await row.getByRole('link', { name: /Build holds for/ }).click()
  const hold = page.getByRole('dialog', { name: 'Build holds', exact: true })
  const positionId = new URL(page.url()).hash.split('/').at(-2)!
  async function reserve(project: string, quantity: number) {
    await hold.getByRole('button', { name: 'Create build hold' }).click()
    await hold.getByLabel('Build or project').fill(project)
    await hold.getByLabel('Confirm physical bin code').fill(f.a.code)
    await hold.getByLabel('Quantity to reserve').fill(String(quantity))
    await hold.getByLabel('Reason', { exact: true }).fill('Project allocation')
    await hold.getByRole('button', { name: 'Confirm hold' }).click()
    await expect(hold).toContainText('Reserved ' + quantity + ' for ' + project)
  }
  await reserve('Bridge build', 1)
  await reserve('Tower build', 2)
  await expect(hold.getByRole('button', { name: 'Create build hold' })).toBeDisabled()
  await hold.getByRole('button', { name: 'Close build holds' }).click()
  await row.getByRole('button', { name: /Transfer stock from/ }).click()
  const transfer = page.getByRole('dialog', { name: 'Transfer stock', exact: true })
  await expect(transfer).toContainText('3 reserved for builds · 3 can move, including 0 without offer backing.')
  await expect(transfer.getByLabel('Count moved')).toHaveAttribute('max', '3')
  await expect(transfer.getByRole('checkbox', { name: /Move the whole position/ })).toBeDisabled()
  await transfer.getByRole('combobox', { name: 'Destination bin', exact: true }).selectOption(f.b.id)
  await transfer.getByLabel('Confirm source bin code').fill(f.a.code)
  await transfer.getByLabel('Confirm destination bin code').fill(f.b.code)
  await transfer.getByLabel('Count moved').fill('1')
  await transfer.getByLabel('Reason', { exact: true }).fill('One unit without offer backing')
  await transfer.getByRole('button', { name: 'Confirm transfer' }).click()
  await expect(transfer.getByRole('alert')).toContainText('available unbacked units')
  await transfer.getByRole('button', { name: 'Cancel' }).click()
  await row.getByRole('link', { name: /Count stock for/ }).click()
  const count = page.getByRole('dialog', { name: 'Count stock', exact: true })
  await count.getByLabel('Confirm physical bin code').fill(f.a.code)
  await count.getByLabel('Witnessed quantity').fill('2')
  await count.getByLabel('Reason for count').fill('Witnessed shortage before build')
  await count.getByRole('button', { name: 'Record observation' }).click()
  const countReceipt = page.getByRole('dialog', { name: 'Count receipt' })
  await countReceipt.getByRole('link', { name: 'Review build holds for this shortage' }).click()
  const holds = hold.getByRole('list', { name: 'Project holds' })
  const bridge = holds.getByRole('listitem').filter({ hasText: 'Bridge build' })
  const tower = holds.getByRole('listitem').filter({ hasText: 'Tower build' })
  await expect(bridge).toContainText('1 held · 0 released of 1')
  await expect(tower).toContainText('2 held · 0 released of 2')
  await expect(hold).toContainText('This position has an open shortage')
  await page.screenshot({ path: info.outputPath('hold-selection-desktop.png') })
  await tower.getByRole('button', { name: 'Release pieces from Tower build' }).click()
  await page.setViewportSize({ width: 320, height: 720 })
  await hold.getByLabel('Quantity to release').fill('1')
  await hold.getByLabel('Reason', { exact: true }).fill('Owner released one tower unit')
  await expect(hold.getByRole('button', { name: 'Confirm release' })).toBeEnabled()
  await page.screenshot({ path: info.outputPath('hold-release-mobile.png') })
  expect(await hold.evaluate(e => e.scrollWidth <= e.clientWidth)).toBe(true)
  await audit(page)
  let body = ''
  await page.route('**/api/v1/receiving/holds/release', async route => {
    body = route.request().postData()!
    const response = await route.fetch()
    expect(response.ok()).toBe(true)
    await response.dispose()
    await route.abort('connectionreset')
  }, { times: 1 })
  await hold.getByRole('button', { name: 'Confirm release' }).click()
  const pending = page.getByRole('region', { name: 'Pending confirmations' })
  await expect(pending).toContainText('Release of 1 held unit')
  await page.reload()
  const replay = page.waitForRequest(req => req.url().endsWith('/receiving/holds/release') && req.method() === 'POST')
  await pending.getByRole('button', { name: 'Retry command' }).click()
  expect((await replay).postData()).toBe(body)
  await expect(pending).toHaveCount(0)
  await page.goto('/' + holdPositionLink(f.a.id, positionId))
  await expect(bridge).toContainText('1 held · 0 released of 1')
  await expect(tower).toContainText('1 held · 1 released of 2')
  await tower.getByRole('button', { name: 'Release history' }).click()
  const history = tower.getByRole('region', { name: 'Release history' })
  await expect(history.getByText('1 released · Owner released one tower unit')).toHaveCount(1)
  await history.getByRole('link', { name: 'Witnessed count for this decision' }).click()
  await expect(countReceipt).toContainText('Open shortage')
  await expect(countReceipt).toContainText('Witnessed shortage before build')
})
