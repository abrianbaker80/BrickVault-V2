import { expect, type Page } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { test } from './trusted'
import { audit, fixture, purchases, stock } from './bin-fixture'
import { closureLink, countPositionLink, countReceiptLink, lossCaseLink } from '../src/countLinks'

const form=(p:Page)=>p.getByRole('dialog',{name:'Close shortage after exact recount',exact:true})
const proof=(p:Page)=>p.getByRole('dialog',{name:'Shortage closure receipt',exact:true})
const counts=(p:Page)=>p.getByRole('dialog',{name:'Count stock',exact:true})
const witness=(p:Page)=>p.getByRole('dialog',{name:'Count receipt',exact:true})
const submit=(p:Page)=>form(p).getByRole('button',{name:'Confirm shortage closure',exact:true})
const endpoint='**/api/v1/receiving/shortage-closures'
const refresh=(p:Page)=>p.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')))

async function shortage(page:Page) {
  const f=await fixture(page), reference='BRIDGE-'+f.a.code
  const purchaseId=await f.write('receiving/purchases',0,{reference,source:'Fictional recount tray',currency:'USD',orderedQuantity:8,pendingChargeMinor:null})
  const deliveryId=await f.write('receiving/deliveries',1,{purchaseId,reference:'Bridge pieces',catalogId:f.catalogId,quantity:8,itemCostMinor:800})
  const position=await f.write('receiving/putaway',2,{purchaseId,deliveryId,catalogId:f.catalogId,locationId:f.a.id,confirmedLocationCode:f.a.code,quantity:8})
  const base={purchaseId,positionId:position,locationId:f.a.id,confirmedLocationCode:f.a.code}
  const hold=await f.write('receiving/holds',3,{...base,quantity:2,purpose:'Named bridge build',reason:'Keep bridge pieces reserved'})
  const offer=await f.write('receiving/offers',4,{purchaseId,catalogId:f.catalogId,unitPriceMinor:175,backing:[{placementId:position,quantity:3}]})
  const damage=await f.write('inventory/quarantines',5,{...base,quantity:2,reason:'Inspect two cracks',catalogId:f.catalogId,catalogRevision:1})
  const opening=await f.write('receiving/counts',6,{...base,countedQuantity:5,reason:'Three pieces absent'})
  return {...f,reference,purchaseId,deliveryId,position,base,hold,offer,damage,opening}
}

test('an operator closes an exact later recount, with retained commitments and receipts after a lost acknowledgement',async ({page},info)=>{
  const f=await shortage(page)
  const surplus=await f.write('receiving/counts',7,{...f.base,countedQuantity:9,reason:'One unidentified piece counted'})
  await page.goto('/'+countReceiptLink(f.a.id,surplus))
  await expect(witness(page)).toContainText('The latest recount found a surplus.')
  await expect(witness(page).getByRole('link',{name:'Review exact recount and close shortage'})).toHaveCount(0)
  await witness(page).getByRole('link',{name:'See counts for this position'}).click()
  await counts(page).getByLabel('Confirm physical bin code').fill(f.a.code)
  await counts(page).getByLabel('Witnessed quantity').fill('8')
  await counts(page).getByLabel('Reason for count').fill('All eight bridge pieces witnessed')
  await counts(page).getByRole('button',{name:'Record observation'}).click()
  await expect(witness(page)).toContainText('The shortage remains open until an operator confirms closure.')
  const exact=page.url().split('/').at(-1)!
  const reviewLink=witness(page).getByRole('link',{name:'Review exact recount and close shortage'})
  await reviewLink.press('Enter')
  const d=form(page)
  await expect(d.getByLabel('Evidence for closure').locator('dd')).toHaveText(['8','8','2','2','3',/8\.00/])
  await expect(d.getByRole('link',{name:'Opening count receipt'})).toHaveAttribute('href',countReceiptLink(f.a.id,f.opening))
  await expect(d.getByRole('link',{name:'Witnessed recount receipt'})).toHaveAttribute('href',countReceiptLink(f.a.id,exact))
  await expect(submit(page)).toBeDisabled()
  await d.getByLabel('Confirm physical bin code').fill(f.b.code)
  await d.getByLabel('Reason for closure').fill('The labelled tray contains all eight bridge pieces')
  await d.getByRole('checkbox').press('Space')
  await expect(submit(page)).toBeDisabled()
  await d.getByLabel('Confirm physical bin code').fill(f.a.code)
  await page.setViewportSize({width:320,height:760})
  expect(await d.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
  const facts=await d.getByLabel('Evidence for closure').boundingBox()
  const links=await d.getByRole('navigation',{name:'Count evidence'}).boundingBox()
  expect(links!.y).toBeGreaterThanOrEqual(facts!.y+facts!.height-1)
  await audit(page)
  await submit(page).focus()
  await d.screenshot({path:info.outputPath('close-exact-recount-mobile.png')})
  let original='',saved=''
  await page.route(endpoint,async route=>{
    original=route.request().postData()!
    const response=await route.fetch()
    expect(response.status()).toBe(200)
    saved=(await response.json()).entityId
    await response.dispose();await route.abort('connectionreset')
  },{times:1})
  await page.keyboard.press('Enter')
  const retry=page.getByRole('button',{name:'Retry command'})
  await expect(retry).toBeVisible()
  await page.reload()
  await page.route(endpoint,async route=>{
    expect(route.request().postData()).toBe(original)
    await route.fulfill({status:413,json:{code:'request_too_large',message:'Request size exceeds the limit.',correlationId:randomUUID()}})
  })
  const lookup=(u:URL)=>u.pathname.endsWith('/shortages/'+f.opening+'/closure') && u.searchParams.has('commandId')
  for (const mismatch of ['partial', 'reason', 'opening observation']) {
    await page.route(lookup,async route=>{
      const response=await route.fetch()
      const receipt=await response.json()
      if (mismatch==='partial') receipt.complete=false
      else if (mismatch==='reason') receipt.reason='Other operator evidence'
      else receipt.openingObservation.id=randomUUID()
      await route.fulfill({response,json:receipt});await response.dispose()
    },{times:1})
    await retry.click()
    await expect(page.getByRole('alert').filter({hasText:'Reconnect to verify'})).toBeVisible()
    await page.getByRole('button',{name:'Refresh',exact:true}).click()
  }
  await retry.click()
  await page.getByRole('link',{name:'View shortage closure receipt'}).click()
  const url=closureLink(f.a.id,f.position,f.opening,'receipt',saved)
  await expect(page).toHaveURL(new RegExp(url+'$'))
  await expect(proof(page).getByLabel('Stock at closure').locator('dd')).toHaveText(['8','5','8','2','2','3',/8\.00/])
  await page.reload()
  await expect(proof(page)).toContainText('The labelled tray contains all eight bridge pieces')
  const balances=await proof(page).getByLabel('Stock at closure').boundingBox()
  const nav=await proof(page).getByRole('navigation',{name:'Closure receipt navigation'}).boundingBox()
  expect(nav!.y).toBeGreaterThanOrEqual(balances!.y+balances!.height-1)
  await page.setViewportSize({width:1440,height:900})
  await proof(page).screenshot({path:info.outputPath('exact-closure-receipt-desktop.png')})
  const [p]=await purchases(page,[f.purchaseId])
  expect(p.balances).toMatchObject({physicalOnHand:8,unavailable:2,reserved:2,backedQuantity:3,knownItemCostMinor:800})
  expect(p.deliveries[0]).toMatchObject({quantity:8,lostQuantity:0,itemCostMinor:800})
  for (const id of [f.opening,surplus,exact]) {
    await page.goto('/'+countReceiptLink(f.a.id,id))
    await expect(witness(page).getByRole('link',{name:'View shortage closure receipt'})).toHaveAttribute('href',url)
    await expect(witness(page)).toContainText(id===exact?'The operator used this witnessed recount':'A later witnessed recount')
    await expect(witness(page).getByRole('region',{name:'Open shortage'})).toHaveCount(0)
  }
  await page.goto('/'+lossCaseLink(f.a.id,f.position,f.opening))
  await expect(page.getByRole('dialog',{name:'Post stock loss',exact:true}).getByRole('link',{name:'View shortage closure receipt'})).toHaveAttribute('href',url)
  await page.goto('/#inventory/'+f.position)
  await expect(page.getByRole('region',{name:'Position timeline'}).getByRole('link',{name:'View shortage closure receipt'})).toHaveAttribute('href',url)
  await page.goto('/#inventory/lot/'+f.deliveryId)
  await expect(page.getByRole('region',{name:'Receipt lot activity'}).getByRole('link',{name:'View shortage closure receipt'})).toHaveAttribute('href',url)
  await page.goto('/#locations/'+f.a.id)
  const layer=stock(page).getByRole('listitem').filter({hasText:f.reference})
  await expect(layer.getByRole('button',{name:/Transfer stock/})).toBeEnabled()
  const reopened=await f.write('receiving/counts',p.revision,{...f.base,countedQuantity:7,reason:'A new shortage after closure'})
  await page.goto('/'+countReceiptLink(f.a.id,exact))
  await expect(witness(page).getByRole('region',{name:'Shortage closures'}).getByRole('link')).toHaveAttribute('href',url)
  await expect(witness(page).getByRole('region',{name:'Open shortage'})).toHaveCount(0)
  await page.goto('/'+countReceiptLink(f.a.id,reopened))
  await expect(witness(page).getByRole('region',{name:'Open shortage'})).toContainText(reopened)
  await expect(witness(page).getByRole('region',{name:'Shortage closures'})).toHaveCount(0)
  await page.goto('/'+countPositionLink(f.a.id,f.position))
  await expect(counts(page).getByRole('region',{name:'Open shortage'})).toContainText(reopened)
  await expect(counts(page).getByRole('region',{name:'Shortage closures'}).getByRole('link')).toHaveAttribute('href',url)
})

test('partial, foreign and superseded recount evidence fences closure and keeps unrelated cases scoped',async ({page,context})=>{
  const f=await shortage(page), reason='All eight confirmed under the correct label'
  const exact=await f.write('receiving/counts',7,{...f.base,countedQuantity:8,reason})
  const routeUrl=closureLink(f.a.id,f.position,f.opening,'review',exact)
  const lookup=(u:URL)=>u.pathname.endsWith('/shortages/'+f.opening+'/adjustment-review')
  await page.route(lookup,async route=>{
    const response=await route.fetch()
    await route.fulfill({response,json:{...await response.json(),complete:false}})
    await response.dispose()
  },{times:1})
  await page.goto('/'+routeUrl)
  await expect(form(page)).toContainText('Incomplete closure review')
  await expect(submit(page)).toHaveCount(0)
  await form(page).getByRole('button',{name:'Retry closure read'}).click()
  await form(page).getByLabel('Confirm physical bin code').fill(f.a.code)
  await form(page).getByLabel('Reason for closure').fill(reason)
  await form(page).getByRole('checkbox').check()
  await expect(submit(page)).toBeEnabled()
  await context.setOffline(true)
  await expect(submit(page)).toBeDisabled()
  await context.setOffline(false)
  await expect(submit(page)).toBeEnabled()
  const newer=await f.write('receiving/counts',8,{...f.base,countedQuantity:6,reason:'Another two absent'})
  await refresh(page)
  await expect(form(page)).toContainText('The count, bin or purchase changed.')
  await expect(submit(page)).toBeDisabled()
  await expect(form(page).getByRole('link',{name:'Review latest witnessed count'})).toHaveAttribute('href',countReceiptLink(f.a.id,newer))
  await page.goto('/'+closureLink(f.a.id,f.position,f.opening,'review',newer))
  await expect(form(page)).toContainText('Closure requires a later witnessed count matching the current ledger.')
  await expect(submit(page)).toBeDisabled()
  await page.goto('/'+closureLink(f.b.id,f.position,f.opening,'review',newer))
  await expect(form(page)).toContainText('No matching closure or open case')
  await expect(form(page).getByLabel('Evidence for closure')).toHaveCount(0)
  await page.goto('/'+countPositionLink(f.a.id,f.position))
  await expect(counts(page).getByRole('region',{name:'Open shortage'})).toHaveCount(1)
  await f.write('receiving/stock-losses',9,{...f.base,caseId:f.opening,expectedObservationId:newer,
    reason:'Counted two missing from the damaged record',offerReductions:[],quarantineAttributions:[{quarantineId:f.damage,quantity:2}]})
  await page.goto('/'+routeUrl)
  await expect(form(page).getByRole('link',{name:'View posted stock loss'})).toBeVisible()
  await expect(form(page).getByRole('link',{name:'View shortage closure receipt'})).toHaveCount(0)
  await expect(submit(page)).toHaveCount(0)
})
