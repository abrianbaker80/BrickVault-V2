for (const releasing of [false,true]) test('lost '+(releasing ? 'inspection release' : 'quarantine')+' acknowledgement reconciles every immutable input and keeps uncertain or incomplete receipts pending',async ({page})=>{
  const f=await eight(page), url=quarantineLink(f.a.id,f.positionId)
  await page.goto('/'+url)
  const view=detail(page)
  if (releasing) {
    await f.write('inventory/quarantines',5,{purchaseId:f.purchaseId,positionId:f.positionId,locationId:f.a.id,confirmedLocationCode:f.a.code,
      catalogId:f.catalogId,catalogRevision:1,quantity:2,reason:'Early inspection record'})
    await page.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')))
    await view.getByRole('button',{name:/Inspect and release from Early inspection record/}).click()
  } else await view.getByRole('button',{name:'Quarantine pieces'}).click()
  const reason=releasing ? 'Inspected one piece under light' : 'Counted two chipped pieces'
  await begin(page,f.a.code,releasing ? 1 : 2,reason,releasing)
  if(releasing) await view.getByRole('checkbox',{name:/I inspected these pieces/}).check()
  let submitted='', saved=''
  const post='**/api/v1/inventory/'+(releasing ? 'quarantine-releases' : 'quarantines')
  await page.route(post,async route=>{
    submitted=route.request().postData()!
    const response=await route.fetch()
    expect(response.ok()).toBe(true)
    saved=(await response.json()).entityId
    await response.dispose()
    await route.abort('connectionreset')
  },{times:1})
  await view.getByRole('button',{name:releasing ? 'Confirm inspected release' : 'Confirm quarantine'}).click()
  const retry=page.getByRole('button',{name:'Retry command'})
  await expect(retry).toBeVisible()
  await page.reload()
  await page.route(post,async route=>{
    expect(route.request().postData()).toBe(submitted)
    await route.fulfill({status:413,json:{code:'request_too_large',message:'Request size exceeds the limit.',correlationId:randomUUID()}})
  })
  const exact=(u:URL)=>u.pathname===read(f.positionId)+'/receipts' && u.searchParams.get('commandId')===JSON.parse(submitted).commandId
  for(const updates of [{complete:false},{reason:'Different reason'}]) {
    await page.route(exact,async route=>{
      const response=await route.fetch()
      await route.fulfill({response,json:{...await response.json(),...updates}})
      await response.dispose()
    },{times:1})
    await retry.click()
    await expect(page.getByRole('alert').filter({hasText:'Reconnect to verify'})).toBeVisible()
    await page.getByRole('button',{name:'Refresh',exact:true}).click()
    await expect(retry).toBeEnabled()
  }
  await retry.click()
  await page.getByRole('link',{name:'View quarantine receipt'}).click()
  await expect(receipt(page)).toContainText(reason)
  expect(page.url()).toContain(quarantineLink(f.a.id,f.positionId,saved))
  const result=await current(page,f.positionId)
  expect(result.quarantines).toHaveLength(1)
  expect(result.quarantinedQuantity).toBe(releasing ? 1 : 2)
})

test('incomplete, wrong-position and offline reads fence drafts; a later catalog revision requires renewed physical identity confirmation',async ({page,context})=>{
  const f=await eight(page)
  const path=read(f.positionId), snap=await current(page,f.positionId)
  const match=(u:URL)=>u.pathname===path
  await page.route(match,r=>r.fulfill({json:{...snap,complete:false}}),{times:1})
  await page.goto('/'+quarantineLink(f.a.id,f.positionId))
  const view=detail(page)
  await expect(view).toContainText('Partial quarantine read.')
  await expect(view).not.toContainText('No quarantine records')
  await view.getByRole('button',{name:'Retry quarantine read'}).click()
  await view.getByRole('button',{name:'Quarantine pieces'}).click()
  await begin(page,f.a.code,1,'Inspect print condition')
  const save=view.getByRole('button',{name:'Confirm quarantine'})
  await expect(save).toBeEnabled()
  await page.route(match,r=>r.fulfill({json:{...snap,position:{...snap.position,layer:{...snap.position.layer,placementId:randomUUID()}}}}),{times:1})
  await page.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')))
  await expect(view).toContainText('could not verify the server response')
  await expect(save).toBeDisabled()
  await view.getByRole('button',{name:'Retry quarantine read'}).click()
  await expect(save).toBeEnabled()
  await context.setOffline(true)
  await expect(save).toBeDisabled()
  await context.setOffline(false)
  await expect(save).toBeEnabled()
  await f.revise()
  await page.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')))
  await expect(view).toContainText('The stock or catalog changed.')
  await expect(save).toBeDisabled()
  await view.getByRole('button',{name:'Cancel'}).click()
  await expect(view.getByRole('button',{name:'Quarantine pieces'})).toBeFocused()
  await view.getByRole('button',{name:'Quarantine pieces'}).click()
  const identity=view.getByRole('checkbox',{name:/I confirmed.*catalog revision 2/})
  await expect(identity).not.toBeChecked()
  await begin(page,f.a.code,1,'Inspect revised catalog identity')
  await save.click()
  await expect(receipt(page)).toContainText('Revision 2')
  const observation=await f.write('receiving/counts',6,{purchaseId:f.purchaseId,positionId:f.positionId,locationId:f.a.id,
    confirmedLocationCode:f.a.code,countedQuantity:7,reason:'One absent from the full tray'})
  await receipt(page).getByRole('link',{name:'Current position quarantine'}).click()
  await expect(view).toContainText('An open shortage blocks quarantine and release')
  await expect(view.getByRole('button',{name:'Quarantine pieces'})).toBeDisabled()
  await expect(view.getByRole('button',{name:/Inspect and release/})).toBeDisabled()
  await page.goto('/'+lossCaseLink(f.a.id,f.positionId,observation))
  await expect(page.getByText(/The count does not identify which pieces are missing/)).toBeVisible()
  await expect(page.getByRole('button',{name:'Post stock loss and selected reductions'})).toBeDisabled()
})
