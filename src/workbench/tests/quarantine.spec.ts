const detail = (p:Page) => p.getByRole('dialog',{name:'Position quarantine',exact:true})
const receipt = (p:Page) => p.getByRole('dialog',{name:'Quarantine receipt',exact:true})
const read = (id:string) => '/api/v1/inventory/positions/'+id+'/quarantine'
async function eight(page:Page) {
  const f = await fixture(page)
  const reference='TRAY-'+f.a.code
  const purchaseId=await f.write('receiving/purchases',0,{reference,source:'Fictional inspection tray',currency:'USD',orderedQuantity:8,pendingChargeMinor:null})
  const deliveryId=await f.write('receiving/deliveries',1,{purchaseId,reference:'Tray of eight',catalogId:f.catalogId,quantity:8,itemCostMinor:800})
  const positionId=await f.write('receiving/putaway',2,{purchaseId,deliveryId,catalogId:f.catalogId,locationId:f.a.id,confirmedLocationCode:f.a.code,quantity:8})
  await f.write('receiving/holds',3,{purchaseId,positionId,locationId:f.a.id,confirmedLocationCode:f.a.code,quantity:2,purpose:'Bridge model',reason:'Two pieces reserved'})
  await f.write('receiving/offers',4,{purchaseId,catalogId:f.catalogId,unitPriceMinor:125,backing:[{placementId:positionId,quantity:3}]})
  return { ...f, reference,purchaseId,deliveryId,positionId }
}
async function current(page:Page,id:string):Promise<QuarantineSnapshot> {
  const response=await page.request.get(read(id))
  expect(response.ok()).toBe(true)
  return response.json()
}
async function begin(page:Page, bin:string, quantity:number, reason:string, release=false) {
  const dialog=detail(page)
  await dialog.getByLabel('Confirm physical bin code').fill(bin)
  await dialog.getByLabel(release ? 'Quantity inspected and approved' : 'Quantity to quarantine').fill(String(quantity))
  await dialog.getByLabel(release ? 'Inspection evidence and reason' : 'Reason for quarantine').fill(reason)
  await dialog.getByRole('checkbox',{name:/I confirmed/}).check()
}
