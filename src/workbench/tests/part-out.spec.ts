async function layer(page:Page,quantity:number,cost:number|null) {
  const f=await fixture(page)
  const catalog=(number:string,name:string,type:string)=>f.write('catalog',0,{itemType:type,itemNumber:number+'-'+f.a.code,name,
    variant:null,colorState:'known',colorId:7,condition:'used',completeness:'complete',source:'Synthetic part-out',license:'operator-owned',mapping:'confirmed'})
  const set=await catalog('SET','Workshop vehicle','set'),axle=await catalog('AX','Axle','part'),figure=await catalog('FIG','Driver','minifigure')
  const purchaseId=await f.write('receiving/purchases',0,{reference:'PART-'+f.a.code,source:'Fictional supplier',currency:'USD',orderedQuantity:quantity,pendingChargeMinor:null})
  const deliveryId=await f.write('receiving/deliveries',1,{purchaseId,reference:'Workshop carton',catalogId:set,quantity,itemCostMinor:cost})
  const position=await f.write('receiving/putaway',2,{purchaseId,deliveryId,catalogId:set,locationId:f.a.id,confirmedLocationCode:f.a.code,quantity})
  return {f,set,axle,figure,purchaseId,deliveryId,position,base:{purchaseId,positionId:position,locationId:f.a.id,confirmedLocationCode:f.a.code}}
}
const form=(page:Page)=>page.getByRole('region',{name:'Manual part-out',exact:true})
const receipt=(page:Page)=>page.getByRole('region',{name:'Part-out receipt',exact:true})
const line=(page:Page,n:number)=>form(page).getByRole('group',{name:'Output '+n,exact:true})
const submit=(page:Page)=>form(page).getByRole('button',{name:'Record part-out',exact:true})
const post='**/api/v1/receiving/part-outs'
async function reopenPending(page:Page,workspaceId:string,body:PartOutCommand) {
  await page.evaluate(({workspaceId,body})=>localStorage.setItem('brickvault.v2.pending.'+workspaceId+'.'+body.commandId,
    JSON.stringify({workspaceId,kind:'part-out',body})),{workspaceId,body})
  await page.reload()
  const pending=page.getByRole('region',{name:'Pending confirmations'})
  await expect(pending.getByRole('button',{name:'Retry command'})).toBeEnabled()
  return pending
}
async function output(page:Page,n:number,catalog:string,bin:{id:string;code:string},quantity:string,
 disposition:'stock'|'retained',cost?:string) {
  const row=line(page,n)
  await row.getByRole('combobox',{name:'Output item',exact:true}).selectOption(catalog)
  await row.getByLabel('Output quantity').fill(quantity)
  await row.getByRole('combobox',{name:'Output disposition',exact:true}).selectOption(disposition)
  await row.getByRole('combobox',{name:'Output bin',exact:true}).selectOption(bin.id)
  await row.getByLabel('Confirm output bin code').fill(bin.code)
  if(cost!==undefined) {
    await row.getByRole('combobox',{name:'Output cost basis'}).selectOption(cost==='unassigned' ? 'unassigned' : 'known')
    if(cost!=='unassigned') await row.getByLabel('Assigned cost').fill(cost)
  }
}
async function review(page:Page,position:string,code:string) {
  await page.goto('/#inventory/'+position)
  const enter=page.getByRole('link',{name:'Record a manual part-out'})
  await enter.focus();await page.keyboard.press('Enter')
  await expect(page).toHaveURL(u=>u.hash===partOutLink(position))
  await form(page).getByLabel('Input units consumed').fill('1')
  await form(page).getByLabel('Confirm input bin code').fill(code)
}
