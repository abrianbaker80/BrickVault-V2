import { test, expect } from '@playwright/test'

for (const engine of ['react', 'vue'])
  test(engine + ' keyboard-only selection and inspection', async ({ page }) => {
    await page.setViewportSize({ width: 900, height: 760 })
    await page.goto('/?engine=' + engine)
    const search = page.getByRole('searchbox')
    await expect(search).toBeVisible()
    await page.keyboard.press('/')
    await expect(search).toBeFocused()
    await page.keyboard.type('BV-1024')
    await expect(page.locator('tbody tr')).toHaveCount(1)
    const select = page.getByRole('checkbox', { name: 'Select BV-1024' })
    for (let i = 0; i < 12 && !(await select.evaluate((el) => el === document.activeElement)); i++)
      await page.keyboard.press('Tab')
    await expect(select).toBeFocused()
    await page.keyboard.press('Space')
    await expect(select).toBeChecked()
    await page.keyboard.press('Tab')
    const inspect = page.getByRole('button', { name: /Inspect .*BV-1024/ })
    await expect(inspect).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('dialog', { name: 'Lot inspector' })).toContainText('B-04')
    await page.keyboard.press('Escape')
    await expect(inspect).toBeFocused()
    await page.keyboard.press('/')
    await page.keyboard.press('Shift+Tab')
    const preview = page.getByRole('button', { name: 'Preview recount' })
    await expect(preview).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('list', { name: 'Frozen targets' })).toContainText('BV-1024')
    await page.keyboard.press('Escape')
    await expect(preview).toBeFocused()
  })
